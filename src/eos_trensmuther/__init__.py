# The package root deliberately retains the broad historical export surface
# above for compatibility. New code should use only PUBLIC_API_NAMES.
from ._api import PUBLIC_API_GROUPS, PUBLIC_API_NAMES, PUBLIC_API_VERSION
from ._contracts import V1_CONTRACT_VERSIONS

_COMPATIBILITY_EXPORTS = tuple(__all__)
_MISSING_PUBLIC_NAMES = tuple(
    name for name in PUBLIC_API_NAMES if name not in globals()
)
if _MISSING_PUBLIC_NAMES:
    raise RuntimeError(
        "frozen public API names are unavailable: %s"
        % ", ".join(_MISSING_PUBLIC_NAMES)
    )

COMPATIBILITY_API_NAMES = tuple(
    name for name in _COMPATIBILITY_EXPORTS if name not in PUBLIC_API_NAMES
)
__all__ = list(
    dict.fromkeys(
        PUBLIC_API_NAMES
        + _COMPATIBILITY_EXPORTS
        + ("COMPATIBILITY_API_NAMES",)
    )
)

del _COMPATIBILITY_EXPORTS
del _MISSING_PUBLIC_NAMES
